// writeevents.vectors.test.ts — ready-b2b done-condition 3: the browser's write
// path replays testdata/write.vectors.json, THE SAME FILE cmd/rd's suite runs
// (cmd/rd/writevectors_test.go), and must reproduce every pinned event
// byte-for-byte: kind, the FULL tag array in the exact emission order (§19.5),
// and content.
//
// It is deliberately the same file, not a copy. A copy would drift, and drift is
// precisely the failure this milestone exists to prevent — the client and rd
// silently disagreeing about event shape. If a vector fails here, the BROWSER is
// wrong: the vector is what rd's real writer actually emits (it is generated by
// replaying rd's own un-exported run*Nostr bodies), so never edit the vector to
// make this pass.
//
// It also replays the round-trip: the produced events are REALLY SIGNED (a real
// secp256k1 key via schnorrsign.ts) and folded back through the shipped
// projection (lib/fold.ts's projectItems, the TS mirror of pkg/sync.ProjectItems
// that internal/foldvectors pins) and compared against the vector's post_fold.
// A write the reader cannot read back is the failure the whole item exists to
// prevent.
